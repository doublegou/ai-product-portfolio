file_arg <- grep("^--file=", commandArgs(), value = TRUE)
if (length(file_arg) != 1L) stop("Run this file with Rscript.", call. = FALSE)
script_path <- normalizePath(sub("^--file=", "", file_arg), mustWork = TRUE)
source(file.path(dirname(script_path), "common.R"), local = TRUE)
context <- supplement_context(script_path)

output_path <- supplement_path(context, context$config$output$processed)
manifest_path <- supplement_path(context, context$config$output$manifest)
supplement_assert(file.exists(output_path), paste("Missing processed release:", output_path))
supplement_assert(file.exists(manifest_path), paste("Missing processed manifest:", manifest_path))

release <- data.table::fread(output_path, encoding = "UTF-8", na.strings = c("", "NA"))
manifest <- jsonlite::read_json(manifest_path, simplifyVector = TRUE)
supplement_assert(nrow(release) == as.integer(context$config$contract$rows), "Processed row count differs from the contract.")
supplement_assert(!anyDuplicated(release$supplement_id), "Processed supplement_id is not unique.")
supplement_assert(sum(release$qc_include_training) == as.integer(context$config$contract$training_rows), "Processed training eligibility differs from the contract.")
supplement_assert(identical(manifest$output$sha256, supplement_sha256(output_path)), "Processed output hash differs from its manifest.")
supplement_assert(all(as.character(supplement_band(release$sr87_sr86)) == release$sr_band), "Processed Sr-band values are invalid.")
message(sprintf("03 complete: output contract and SHA256 verified: %s", output_path))
