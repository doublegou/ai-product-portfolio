const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE_URL = 'https://seedxdream.com';
const COMPANY_NAME = '北京种梦智能科技有限公司';
const SITE_NAME = 'SeedXDream';
const ORGANIZATION_ID = `${SITE_URL}/#organization`;
const WEBSITE_ID = `${SITE_URL}/#website`;

const PRODUCT_IMAGES = {
  birdtracker: '/assets/apps/birdtracker.webp',
  flickwand: '/assets/apps/flick-wand.webp',
  isstracker: '/assets/apps/iss-tracker-logo.webp',
  mathpuzzle: '/assets/apps/math-puzzle.webp',
  stayword: '/assets/apps/stayword.webp',
};

const PRODUCT_NAMES = {
  birdtracker: 'Bird Tracker',
  flickwand: 'Flick Wand',
  isstracker: 'ISS Tracker',
  mathpuzzle: 'Math Puzzle',
  stayword: 'StayWord',
};

const START_MARKER = '    <!-- SEO metadata: generated by scripts/apply-seo-metadata.js -->';
const END_MARKER = '    <!-- /SEO metadata -->';

function htmlEscape(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
}

function collectHtmlFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === '.git' || entry.name === 'node_modules') return [];
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return collectHtmlFiles(fullPath);
    return entry.name === 'index.html' ? [fullPath] : [];
  });
}

function pagePathFor(filePath) {
  const relativeDir = path.relative(ROOT, path.dirname(filePath)).split(path.sep).join('/');
  return relativeDir ? `/${relativeDir}/` : '/';
}

function pageKind(pagePath) {
  if (pagePath === '/') return 'home';
  const productMatch = pagePath.match(/^\/products\/([^/]+)\/$/);
  if (productMatch) return 'product';
  if (pagePath.endsWith('/privacypolicy/') || pagePath.endsWith('/termofuse/')) return 'webpage';
  return 'article';
}

function productKeyFor(pagePath) {
  return pagePath.split('/').filter(Boolean)[1] || 'stayword';
}

function organizationSchema() {
  return {
    '@type': 'Organization',
    '@id': ORGANIZATION_ID,
    name: COMPANY_NAME,
    alternateName: [SITE_NAME, 'DualariesAI'],
    url: `${SITE_URL}/`,
    logo: `${SITE_URL}/assets/brand/zhongmeng-logo.webp`,
  };
}

function breadcrumbSchema(pagePath, pageTitle) {
  const items = [
    {
      '@type': 'ListItem',
      position: 1,
      name: '首页',
      item: `${SITE_URL}/`,
    },
  ];

  if (pagePath.startsWith('/products/stayword/') && pagePath !== '/products/stayword/') {
    items.push({
      '@type': 'ListItem',
      position: 2,
      name: 'StayWord',
      item: `${SITE_URL}/products/stayword/`,
    });
  }

  items.push({
    '@type': 'ListItem',
    position: items.length + 1,
    name: pageTitle,
    item: `${SITE_URL}${pagePath}`,
  });

  return {
    '@type': 'BreadcrumbList',
    '@id': `${SITE_URL}${pagePath}#breadcrumb`,
    itemListElement: items,
  };
}

function graphFor({ pagePath, pageTitle, description, kind, image }) {
  const canonical = `${SITE_URL}${pagePath}`;
  const graph = [organizationSchema()];

  if (kind === 'home') {
    graph.push({
      '@type': 'WebSite',
      '@id': WEBSITE_ID,
      name: SITE_NAME,
      alternateName: COMPANY_NAME,
      url: `${SITE_URL}/`,
      description,
      publisher: { '@id': ORGANIZATION_ID },
      inLanguage: 'zh-CN',
    });
    return graph;
  }

  if (kind === 'product') {
    const key = productKeyFor(pagePath);
    graph.push({
      '@type': 'SoftwareApplication',
      '@id': `${canonical}#software-application`,
      name: PRODUCT_NAMES[key] || pageTitle,
      url: canonical,
      description,
      image,
      publisher: { '@id': ORGANIZATION_ID },
      inLanguage: 'zh-CN',
    });
  } else {
    graph.push({
      '@type': kind === 'article' ? 'Article' : 'WebPage',
      '@id': `${canonical}#primary-content`,
      headline: pageTitle,
      name: pageTitle,
      url: canonical,
      description,
      image,
      mainEntityOfPage: canonical,
      author: { '@id': ORGANIZATION_ID },
      publisher: { '@id': ORGANIZATION_ID },
      inLanguage: 'zh-CN',
    });
  }

  graph.push(breadcrumbSchema(pagePath, pageTitle));
  return graph;
}

function metadataBlock({ pagePath, title, description }) {
  const kind = pageKind(pagePath);
  const canonical = `${SITE_URL}${pagePath}`;
  const pageTitle = title.split(' | ')[0].trim();
  const productKey = productKeyFor(pagePath);
  const imagePath = kind === 'home'
    ? '/assets/brand/zhongmeng-logo.webp'
    : PRODUCT_IMAGES[productKey] || PRODUCT_IMAGES.stayword;
  const image = `${SITE_URL}${imagePath}`;
  const graph = graphFor({ pagePath, pageTitle, description, kind, image });
  const jsonLd = JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 2)
    .split('\n')
    .map((line) => `      ${line}`)
    .join('\n');

  return [
    START_MARKER,
    `    <link rel="canonical" href="${canonical}" />`,
    '    <meta name="robots" content="index, follow, max-image-preview:large" />',
    '    <meta property="og:locale" content="zh_CN" />',
    `    <meta property="og:site_name" content="${SITE_NAME}" />`,
    `    <meta property="og:type" content="${kind === 'article' ? 'article' : 'website'}" />`,
    `    <meta property="og:title" content="${htmlEscape(title)}" />`,
    `    <meta property="og:description" content="${htmlEscape(description)}" />`,
    `    <meta property="og:url" content="${canonical}" />`,
    `    <meta property="og:image" content="${image}" />`,
    '    <meta name="twitter:card" content="summary" />',
    `    <meta name="twitter:title" content="${htmlEscape(title)}" />`,
    `    <meta name="twitter:description" content="${htmlEscape(description)}" />`,
    `    <meta name="twitter:image" content="${image}" />`,
    '    <script type="application/ld+json">',
    jsonLd,
    '    </script>',
    END_MARKER,
  ].join('\n');
}

function applyMetadata(filePath) {
  let html = fs.readFileSync(filePath, 'utf8');
  const existingBlock = new RegExp(`${START_MARKER}[\\s\\S]*?${END_MARKER}\\n?`, 'g');
  html = html.replace(existingBlock, '');

  const titleMatch = html.match(/<title>([\s\S]*?)<\/title>/);
  const descriptionMatch = html.match(/<meta\s+name="description"\s+content="([\s\S]*?)"\s*\/?>/);
  if (!titleMatch || !descriptionMatch) {
    throw new Error(`Missing title or description: ${path.relative(ROOT, filePath)}`);
  }

  const title = titleMatch[1].replace(/\s+/g, ' ').trim();
  const description = descriptionMatch[1].replace(/\s+/g, ' ').trim();
  const block = metadataBlock({ pagePath: pagePathFor(filePath), title, description });
  html = html.replace(titleMatch[0], `${titleMatch[0]}\n${block}`);
  fs.writeFileSync(filePath, html, 'utf8');
  console.log(`SEO metadata updated: ${path.relative(ROOT, filePath)}`);
}

collectHtmlFiles(ROOT).sort().forEach(applyMetadata);
